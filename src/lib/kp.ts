export type KpLevel = "calm" | "weak" | "moderate" | "strong";

/** NOAA G-scale (0..5) from Kp value (Kp 5- = 4.67 → G1 etc.). */
export function kpToG(kp: number): number {
  if (kp >= 8.67) return 5;
  if (kp >= 7.67) return 4;
  if (kp >= 6.67) return 3;
  if (kp >= 5.67) return 2;
  if (kp >= 4.67) return 1;
  return 0;
}

export function kpLevel(kp: number): KpLevel {
  if (kp < 4) return "calm";
  if (kp < 5.67) return "weak";
  if (kp < 6.67) return "moderate";
  return "strong";
}

export const LEVEL_LABEL: Record<KpLevel, string> = {
  calm: "Спокойно",
  weak: "Слабая буря",
  moderate: "Умеренная буря",
  strong: "Сильная буря",
};

export const LEVEL_COLOR: Record<KpLevel, string> = {
  calm: "#34d399",
  weak: "#facc15",
  moderate: "#fb923c",
  strong: "#f43f5e",
};

export function kpColor(kp: number): string {
  return LEVEL_COLOR[kpLevel(kp)];
}

export function kpLabel(kp: number): string {
  const lvl = kpLevel(kp);
  if (lvl === "weak" && kp < 4.67) return "Слабые возмущения";
  return LEVEL_LABEL[lvl];
}

